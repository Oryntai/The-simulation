//! Динамические модели приводов из каталога.
//!
//! Каталог — файлы `<id>.toml`. В таблице `[parameters]` число задаётся
//! как `{ value = …, source = "measured", reference = "…" }` или как
//! `{ unknown = true, bench = "…" }`. Паспортные точки и результаты
//! стенда можно хранить вместе. Обязательные параметры проверяются при установке.
//!
//! `inertia = "internal"` считает ротор вместе со входом передачи, требует
//! податливую связь и нулевую `armature` на оси. `inertia = "mjcf"`
//! использует жёсткую передачу и инерцию оси. `backlash` — полный свободный
//! ход. Координаты, скорости, усилия и коэффициенты податливости заданы в СИ
//! на выходе (рад/Н·м либо м/Н). Трение и электромеханическая константа заданы
//! со стороны ротора. Для линейного выхода ход за оборот относится к валу
//! после редуктора. `motor_constant` задаёт взаимную константу момента и ЭДС
//! в согласованных единицах. Паспортные `kt_motor_nm_per_a`, `ke_motor_v_s`
//! и токи питания сохраняются как метаданные и требуют такой нормировки.
//!
//! `power_input = true` требует вход с именем `<effort>-power` на той же
//! степени свободы. При отсутствии команды на него питание снято. Вход
//! команды привода защёлкивается рантаймом, задержка отсчитывается от такта,
//! на котором привод увидел новое значение. После доставки регулятор
//! принимает команду на своём очередном такте. Напряжение в истине —
//! усреднённое напряжение моста последнего расчётного подшага.
//!
//! На той же степени свободы можно объявить входы `<effort>-bus-v`
//! в вольтах и `<effort>-bridge` со значениями [BridgeCommand].
//! До первой записи напряжения действует `supply_v`. Снятие разрешения
//! `-power` переводит управляемый мост в выбег. Диоды могут возвращать
//! энергию в шину при гашении тока и при внешнем разгоне выше ЭДС шины.
//! Короткое замыкание даёт ноль вольт и не ограничивает ток регулированием.
//!
//! Для режима положения можно объявить вместе `<effort>-pulse-period`,
//! `<effort>-pulse-width` (секунды) и `<effort>-pulse-seq`. Позиция
//! интерполируется по двум калиброванным точкам. Выход за диапазон
//! периода или ширины снимает команду и очищает очередь задержки.
//! При пропаже кадров отсчёт таймаута идёт от последнего увиденного кадра.
//! В этом режиме прямой вход задания зарезервирован для выхода усилия.
//! Калибровка: `pulse_period_min_s` и `pulse_period_max_s`,
//! `pulse_width_min_s` и `pulse_width_max_s`, `pulse_position_at_min_width`
//! и `pulse_position_at_max_width` в единицах выхода, `pulse_timeout_s`.
//! Параметры экземпляра в `params` имеют приоритет над каталогом.
//!
//! Приводы решаются совместно по текущей матрице масс. Момент или сила
//! в журнале — среднее усилие, которое будет удержано до следующего шага.
//! В балансе ротора используется то же переданное усилие, без внешних
//! усилий упора и удержания, которые приложены напрямую к выходу.
//!
//! Каналы температур существуют только для полной тепловой сети. Расчёт
//! стартует с `initial_winding_temp_c` и `initial_housing_temp_c` либо с температуры
//! среды для каждого узла без начального значения. Сигнал перегрева сообщает
//! превышение заданного порога. `motor_energy_residual_j` учитывает работу
//! на выходе по внутренним подшагам, `world_energy_residual_j` использует
//! фактическую работу удержанного усилия в MuJoCo. Работа упора, тормоза
//! и фиксатора в оба баланса не входит.

