//! `sim-em` — Электромагнетизм: поля токов (Био–Савар), постоянные магниты, электромагнит с сердечником, двигатель с редуктором и нагревом.
//!
//! Модули:
//! * [`math`] — эллиптические интегралы (AGM, `cel` Булирша), J₁, квадратуры;
//! * [`field`] — поля отрезков, ломаных, витков, соленоидов; силовые линии;
//! * [`magnet`] — постоянные магниты NdFeB: поле, сила магнит–магнит и магнит–сталь,
//!   марки и температура, датчик угла на диаметральном магните;
//! * [`magcircuit`] — магнитная цепь с нелинейной сталью, сила удержания, обмотка;
//! * [`motor`] — двигатель постоянного тока / BLDC с редуктором и тепловой моделью.
//!
//! Каждая модель сверяется вторым независимым способом — см. [`reference_checks`];
//! противоречия внутри данных производителей — отдельно, [`datasheet_discrepancies`].
//! Единицы — СИ (м, А, Тл, Н, Н·м, рад/с, Дж); температуры — °C.
//!
//! Ко-симуляция привода сустава (скорость сустава задаёт многотельная модель):
//! ```
//! use sim_em::motor::{Motor, MotorParams};
//! let mut m = Motor::new(MotorParams::maxon_ec90flat_260w_hd_csg25_50());
//! let dt = 1e-3;
//! m.step_electrical(24.0, 0.5, dt); // напряжение на зажимах, ω сустава
//! let tau = m.joint_torque(); // в многотельную модель (+ m.reflected_inertia() как armature)
//! m.step_thermal(dt, 25.0);
//! m.set_housing_to_ambient_k_per_w(0.8); // обдув/вода из sim-env
//! assert!(tau.is_finite() && m.winding_temp_c() >= 25.0 && m.current() != 0.0);
//! ```

pub mod field;
pub mod magcircuit;
pub mod magnet;
pub mod math;
pub mod motor;

/// Магнитная постоянная μ₀, Н/А² (CODATA 2018: 1.25663706212(19)·10⁻⁶;
/// после переопределения СИ 2019 — измеряемая величина, отличие от 4π·10⁻⁷ ≈ 5e-10 отн.).
pub const MU0: f64 = 1.256_637_062_12e-6;

/// Все сверки этого блока с эталоном (вторым независимым способом).
pub fn reference_checks() -> Vec<sim_verify::Check> {
    let mut v = field::checks();
    v.extend(magnet::checks());
    v.extend(magcircuit::checks());
    v.extend(motor::checks());
    v
}

/// Найденные противоречия в данных производителей (не ошибки модели): величины, которые
/// не сходятся между собой внутри одного даташита больше чем на 5 % и которым у нас нет
/// проверяемого объяснения. Не прячем — отдаём отдельным списком; вердикт у них может
/// быть «не пройдено», это находка о данных, а не о модели.
pub fn datasheet_discrepancies() -> Vec<sim_verify::Check> {
    motor::datasheet_discrepancies()
}
