//! `sim-env` — Среда и человек: воздух, вода, ветер, холод, жара; теплообмен, терморегуляция
//! человека, контакт кожи с материалами.
//!
//! Модули:
//! * [`air`] — влажный воздух: давление насыщения (Магнус, Бак, IAPWS), точка росы,
//!   конденсация, плотность (идеальная смесь и CIPM-2007), вязкость, теплопроводность, Pr;
//! * [`water`] — пресная и морская вода (Sharqawy 2010, EOS-80, PSS-78);
//! * [`convection`] — теплоотдача цилиндра, пластины, свободная и смешанная конвекция,
//!   излучение — в воздухе и воде;
//! * [`indices`] — ветро-холодовой индекс и время до обморожения, индекс жары, WBGT (оценка),
//!   шкала Бофорта;
//! * [`two_node`] — двухузловая модель терморегуляции Гагге и SET (ASHRAE 55);
//! * [`immersion`] — погружение в холодную воду: этапы и время охлаждения ядра;
//! * [`strain`] — пределы теплового и холодового напряжения (ядро, обезвоживание);
//! * [`contact`] — касание кожей металла и пластика: температура контакта, ожог, холод;
//! * [`effects`] — мышцы и руки в холоде, нагрев солнцем, пределы материалов, батарей,
//!   электроники, IP-код;
//! * [`checks`] — все сверки со вторым независимым способом.
//!
//! Единицы — СИ, если в имени не сказано иное (`_c` — °C, `_min` — минуты, `_kmh` — км/ч).

pub mod air;
pub mod checks;
pub mod contact;
pub mod convection;
pub mod effects;
pub mod immersion;
pub mod indices;
pub mod strain;
pub mod two_node;
pub mod water;

