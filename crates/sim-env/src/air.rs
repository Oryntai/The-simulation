/// Точка росы, °C, — аналитическое обращение формулы Магнуса (Alduchov–Eskridge).
pub fn dew_point_magnus(t_c: f64, rh_percent: f64) -> f64 {
    let rh = rh_percent.clamp(1e-6, 100.0);
    let g = (rh / 100.0).ln() + 17.625 * t_c / (243.04 + t_c);
    243.04 * g / (17.625 - g)
}

/// Точка росы, °C, — численное обращение эталона [`p_sat`] (IAPWS; ниже 0 °C — Murphy–Koop)
/// бисекцией: p_sat(t_d) = e. Второй, независимый от Магнуса способ.
pub fn dew_point_iapws(t_c: f64, rh_percent: f64) -> f64 {
    let e = vapour_pressure(t_c, rh_percent.max(1e-6));
    bisect(|t| p_sat(t) - e, -100.0, t_c + 1e-9, 1e-10)
}

/// Точка инея (насыщение надо льдом), °C, обращение IAPWS R14-08. Имеет смысл, когда
/// результат ниже 0 °C.
pub fn frost_point_iapws(t_c: f64, rh_percent: f64) -> f64 {
    let e = vapour_pressure(t_c, rh_percent.max(1e-6));
    bisect(|t| p_sat_iapws_ice(t) - e, -120.0, 0.01, 1e-10)
}

/// Точка росы, используемая в крейте (IAPWS), °C.
pub fn dew_point(t_c: f64, rh_percent: f64) -> f64 {
    dew_point_iapws(t_c, rh_percent)
}

/// Результат проверки «холодный прибор внесли в тёплое влажное помещение».
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct CondensationCheck {
    /// Точка росы воздуха помещения, °C.
    pub dew_point_c: f64,
    /// Температура поверхности прибора, °C.
    pub surface_c: f64,
    /// Запас: температура поверхности минус точка росы, К. Отрицательный — будет роса.
    pub margin_k: f64,
    /// Конденсация будет (поверхность холоднее точки росы).
    pub condenses: bool,
    /// Поверхность ниже 0 °C и пар пересыщен надо льдом — оседает иней.
    pub frost: bool,
}

/// Будет ли конденсат на поверхности с температурой `surface_c` в воздухе `t_air_c`, `rh_percent`.
/// Критерий: парциальное давление пара в воздухе выше давления насыщения при температуре
/// поверхности — над водой (роса, эквивалентно «поверхность холоднее точки росы») или,
/// ниже 0 °C, надо льдом (иней: на морозной поверхности пар оседает льдом).
pub fn condensation_check(t_air_c: f64, rh_percent: f64, surface_c: f64) -> CondensationCheck {
    let td = dew_point(t_air_c, rh_percent);
    let e = vapour_pressure(t_air_c, rh_percent);
    let frost = surface_c < 0.0 && e > p_sat_iapws_ice(surface_c);
    CondensationCheck {
        dew_point_c: td,
        surface_c,
        margin_k: surface_c - td,
        condenses: surface_c < td || frost,
        frost,
    }
}

