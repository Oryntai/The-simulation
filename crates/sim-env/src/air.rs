/// Плотность влажного воздуха как смеси идеальных газов, кг/м³:
/// ρ = (p − e)/(R_d·T) + e/(R_v·T).
pub fn density_moist(t_c: f64, rh_percent: f64, p_pa: f64) -> f64 {
    let t = t_c + T0;
    let e = vapour_pressure(t_c, rh_percent).min(p_pa);
    (p_pa - e) / (R_DRY_AIR * t) + e / (R_VAPOUR * t)
}

/// Плотность влажного воздуха по формуле CIPM-2007 (с фактором сжимаемости Z и
/// коэффициентом усиления f), кг/м³. Второй способ для [`density_moist`].
/// Применимость формулы: 600–1100 гПа, 15–27 °C; вне этого — экстраполяция.
///
/// Источник: Picard A., Davis R.S., Gläser M., Fujii K. (2008) Metrologia 45:149–155,
/// doi:10.1088/0026-1394/45/2/004.
pub fn density_cipm2007(t_c: f64, rh_percent: f64, p_pa: f64) -> f64 {
    let t = t_c + T0;
    // давление насыщения по Дэвису (часть CIPM-2007), Па
    let p_sv =
        (1.237_884_7e-5 * t * t - 1.912_131_6e-2 * t + 33.937_110_47 - 6.343_164_5e3 / t).exp();
    let f = 1.000_62 + 3.14e-8 * p_pa + 5.6e-7 * t_c * t_c;
    let x_v = rh_percent.clamp(0.0, 100.0) / 100.0 * f * p_sv / p_pa;
    let (a0, a1, a2) = (1.581_23e-6, -2.9331e-8, 1.1043e-10);
    let (b0, b1) = (5.707e-6, -2.051e-8);
    let (c0, c1) = (1.9898e-4, -2.376e-6);
    let (d, e) = (1.83e-11, -0.765e-8);
    let z = 1.0
        - p_pa / t
            * (a0
                + a1 * t_c
                + a2 * t_c * t_c
                + (b0 + b1 * t_c) * x_v
                + (c0 + c1 * t_c) * x_v * x_v)
        + (p_pa * p_pa) / (t * t) * (d + e * x_v * x_v);
    let m_a = 28.965_46e-3; // x_CO2 = 400 ppm
    let m_v = 18.015_28e-3;
    let r = 8.314_472;
    p_pa * m_a / (z * r * t) * (1.0 - x_v * (1.0 - m_v / m_a))
}

/// Динамическая вязкость сухого воздуха по Сазерленду, Па·с:
/// μ = μ₀·(T/T₀)^1.5·(T₀ + S)/(T + S), μ₀ = 1.716·10⁻⁵ Па·с, T₀ = 273.15 К, S = 110.4 К.
/// Точность ~2 % в 170–1900 К (White F.M., Viscous Fluid Flow, 3rd ed., 2006, табл. 1-2).
pub fn viscosity(t_c: f64) -> f64 {
    let t = t_c + T0;
    1.716e-5 * (t / T0).powf(1.5) * (T0 + 110.4) / (t + 110.4)
}

/// Теплопроводность сухого воздуха (формула Сазерленда для k), Вт/(м·К):
/// k = k₀·(T/T₀)^1.5·(T₀ + S)/(T + S), k₀ = 0.0241, T₀ = 273 К, S = 194 К.
/// Точность ~2 % в 160–2000 К (White, Viscous Fluid Flow, табл. 1-3).
pub fn conductivity(t_c: f64) -> f64 {
    let t = t_c + T0;
    0.0241 * (t / 273.0).powf(1.5) * (273.0 + 194.0) / (t + 194.0)
}

/// Удельная теплоёмкость сухого воздуха, Дж/(кг·К). Наша аппроксимация «оценка»:
/// c_p = 1002.5 + 2.75·10⁻⁴·(T − 200)², сверена с таблицей Incropera A.4 (250–350 К, < 0.3 %).
pub fn cp_dry(t_c: f64) -> f64 {
    let t = t_c + T0;
    1002.5 + 2.75e-4 * (t - 200.0).powi(2)
}

/// Массовая доля водяного пара (удельная влажность), кг/кг.
pub fn specific_humidity(t_c: f64, rh_percent: f64, p_pa: f64) -> f64 {
    let e = vapour_pressure(t_c, rh_percent).min(p_pa);
    let w = 0.621_945 * e / (p_pa - e).max(1.0); // влагосодержание, кг/кг сухого
    w / (1.0 + w)
}

/// Свойства влажного воздуха в одной точке.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct AirProps {
    /// Плотность, кг/м³.
    pub rho: f64,
    /// Динамическая вязкость, Па·с.
    pub mu: f64,
    /// Теплопроводность, Вт/(м·К).
    pub k: f64,
    /// Удельная теплоёмкость, Дж/(кг·К).
    pub cp: f64,
    /// Число Прандтля.
    pub pr: f64,
}

/// Свойства влажного воздуха при `t_c`, `rh_percent`, `p_pa`.
pub fn air_props(t_c: f64, rh_percent: f64, p_pa: f64) -> AirProps {
    let rho = density_moist(t_c, rh_percent, p_pa);
    let mu = viscosity(t_c);
    let k = conductivity(t_c);
    let q = specific_humidity(t_c, rh_percent, p_pa);
    let cp = (1.0 - q) * cp_dry(t_c) + q * CP_VAPOUR;
    AirProps {
        rho,
        mu,
        k,
        cp,
        pr: mu * cp / k,
    }
}

/// Бисекция: корень `f` на [lo, hi] (f(lo) и f(hi) разных знаков).
pub(crate) fn bisect(f: impl Fn(f64) -> f64, mut lo: f64, mut hi: f64, tol: f64) -> f64 {
    let mut flo = f(lo);
    for _ in 0..200 {
        let mid = 0.5 * (lo + hi);
        let fm = f(mid);
        if (fm < 0.0) == (flo < 0.0) {
            lo = mid;
            flo = fm;
        } else {
            hi = mid;
        }
        if hi - lo < tol {
            break;
        }
    }
    0.5 * (lo + hi)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn triple_point_and_boiling() {
        assert!((p_sat_iapws_water(0.01) - 611.657).abs() < 0.01);
        assert!((p_sat_iapws_ice(0.01) - 611.657).abs() < 1e-6);
        // нормальная точка кипения по МТШ-90: 99.974 °C
        assert!((p_sat_iapws_water(99.974) / P_STANDARD - 1.0).abs() < 2e-4);
    }

    #[test]
    fn dew_point_inverts() {
        let td = dew_point(25.0, 60.0);
        assert!((p_sat(td) - vapour_pressure(25.0, 60.0)).abs() < 1e-6);
        assert!((dew_point(20.0, 100.0) - 20.0).abs() < 1e-6);
    }

    #[test]
    fn cold_device_in_warm_room_fogs() {
        // прибор с мороза −10 °C в комнату 22 °C, 50 %: точка росы ≈ 11 °C → роса
        let c = condensation_check(22.0, 50.0, -10.0);
        assert!(c.condenses);
        assert!((c.dew_point_c - 11.1).abs() < 0.3);
        let warm = condensation_check(22.0, 50.0, 18.0);
        assert!(!warm.condenses);
    }
}
