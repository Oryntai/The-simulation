//! Влажный воздух: давление насыщенного пара (три независимые формулы), точка росы,
//! плотность (идеальная смесь и CIPM-2007), вязкость, теплопроводность, теплоёмкость, Pr.
//!
//! Допущения:
//! * Воздух — смесь сухого воздуха и водяного пара; по умолчанию идеальные газы.
//!   Неидеальность (фактор сжимаемости Z ≈ 0.9996 при 20 °C) учитывает только
//!   [`density_cipm2007`] — она служит вторым способом для [`density_moist`].
//! * Вязкость и теплопроводность считаются для сухого воздуха (формулы Сазерленда);
//!   влияние влажности на них < 1–2 % при t < 40 °C и здесь не учитывается.
//! * Давление насыщения «над водой» используется и ниже 0 °C (переохлаждённая вода,
//!   так принято в метеорологии для точки росы); «над льдом» — отдельные функции.

/// 0 °C в кельвинах.
pub const T0: f64 = 273.15;
/// Универсальная газовая постоянная, Дж/(моль·К) (CODATA 2018).
pub const R_UNIVERSAL: f64 = 8.314_462_618;
/// Молярная масса сухого воздуха, кг/моль (CIPM-2007 при x_CO2 = 400 ppm).
pub const M_DRY_AIR: f64 = 0.028_965_46;
/// Молярная масса воды, кг/моль.
pub const M_WATER: f64 = 0.018_015_28;
/// Удельная газовая постоянная сухого воздуха, Дж/(кг·К).
pub const R_DRY_AIR: f64 = R_UNIVERSAL / M_DRY_AIR;
/// Удельная газовая постоянная водяного пара, Дж/(кг·К).
pub const R_VAPOUR: f64 = R_UNIVERSAL / M_WATER;
/// Нормальное атмосферное давление, Па.
pub const P_STANDARD: f64 = 101_325.0;
/// Теплоёмкость водяного пара при постоянном давлении, Дж/(кг·К) (≈ 1.86 кДж/(кг·К) при 0–50 °C).
pub const CP_VAPOUR: f64 = 1860.0;

// ---------------------------------------------------------------------------
// Давление насыщенного пара
// ---------------------------------------------------------------------------

/// Давление насыщения над водой по Магнусу с коэффициентами Alduchov & Eskridge (1996)
/// (формула AERK), Па. Заявленная авторами точность в −40…+50 °C — лучше 0.4 % относительно
/// эталона.
///
/// Источник: Alduchov O.A., Eskridge R.E. (1996) J. Appl. Meteor. 35:601–609,
/// doi:10.1175/1520-0450(1996)035<0601:IMFAOS>2.0.CO;2
pub fn p_sat_magnus_water(t_c: f64) -> f64 {
    610.94 * (17.625 * t_c / (t_c + 243.04)).exp()
}

/// Давление насыщения над льдом по Магнусу (AERKi, Alduchov & Eskridge 1996), Па.
pub fn p_sat_magnus_ice(t_c: f64) -> f64 {
    611.21 * (22.587 * t_c / (t_c + 273.86)).exp()
}

/// Давление насыщения над водой по Баку, Па: e = 611.21·exp((18.678 − t/234.5)·t/(257.14 + t)).
///
/// Форма — Buck A.L. (1981) J. Appl. Meteor. 20:1527–1532,
/// doi:10.1175/1520-0450(1981)020<1527:NEFCVP>2.0.CO;2; коэффициенты — уточнение автора
/// (Buck Research CR-1A User's Manual, 1996). Это другая аппроксимация, чем у Магнуса
/// (есть член t², другая подгонка), поэтому годится как независимая сверка.
pub fn p_sat_buck_water(t_c: f64) -> f64 {
    611.21 * ((18.678 - t_c / 234.5) * (t_c / (257.14 + t_c))).exp()
}

/// Давление насыщения над льдом по Баку (1996), Па.
pub fn p_sat_buck_ice(t_c: f64) -> f64 {
    611.15 * ((23.036 - t_c / 333.7) * (t_c / (279.82 + t_c))).exp()
}

/// Давление насыщения над водой по уравнению Вагнера–Прусса (IAPWS, эталон), Па.
/// Справедливо от тройной точки 273.16 К до критической 647.096 К; ниже 0 °C — экстраполяция
/// на переохлаждённую воду (отклонение от IAPWS-95 малое, проверено авторами до −20 °C).
///
/// Источник: Wagner W., Pruß A. (1993) J. Phys. Chem. Ref. Data 22:783–787,
/// doi:10.1063/1.555926 (IAPWS SR1-86, ред. 1992).
pub fn p_sat_iapws_water(t_c: f64) -> f64 {
    const TC: f64 = 647.096;
    const PC: f64 = 22.064e6;
    const A: [f64; 6] = [
        -7.859_517_83,
        1.844_082_59,
        -11.786_649_7,
        22.680_741_1,
        -15.961_871_9,
        1.801_225_02,
    ];
    let t = t_c + T0;
    let tau = 1.0 - t / TC;
    let s = A[0] * tau
        + A[1] * tau.powf(1.5)
        + A[2] * tau.powi(3)
        + A[3] * tau.powf(3.5)
        + A[4] * tau.powi(4)
        + A[5] * tau.powf(7.5);
    PC * (TC / t * s).exp()
}

/// Давление сублимации льда Ih по IAPWS R14-08 (2011), Па. Эталон для t ≤ 0.01 °C.
///
/// Источник: Wagner W., Riethmann T., Feistel R., Harvey A.H. (2011)
/// J. Phys. Chem. Ref. Data 40:043103, doi:10.1063/1.3657937.
pub fn p_sat_iapws_ice(t_c: f64) -> f64 {
    const TT: f64 = 273.16;
    const PT: f64 = 611.657;
    const A: [f64; 3] = [-0.212_144_006e2, 0.273_203_819e2, -0.610_598_130e1];
    const B: [f64; 3] = [0.333_333_333e-2, 0.120_666_667e1, 0.170_333_333e1];
    let theta = (t_c + T0) / TT;
    let s: f64 = A.iter().zip(B).map(|(a, b)| a * theta.powf(b)).sum();
    PT * (s / theta).exp()
}

/// Давление насыщения над переохлаждённой (и обычной) водой по Murphy & Koop (2005), Па.
/// Применимость 123–332 К; эталон для воды ниже 0 °C, где уравнение IAPWS — экстраполяция.
///
/// Источник: Murphy D.M., Koop T. (2005) Q. J. R. Meteorol. Soc. 131:1539–1565,
/// doi:10.1256/qj.04.94, ур. (10).
pub fn p_sat_murphy_koop_water(t_c: f64) -> f64 {
    let t = t_c + T0;
    (54.842_763 - 6763.22 / t - 4.210 * t.ln()
        + 0.000_367 * t
        + (0.0415 * (t - 218.8)).tanh()
            * (53.878 - 1331.22 / t - 9.445_23 * t.ln() + 0.014_025 * t))
        .exp()
}

/// Давление сублимации льда по Murphy & Koop (2005), ур. (7), Па; T > 110 К.
pub fn p_sat_murphy_koop_ice(t_c: f64) -> f64 {
    let t = t_c + T0;
    (9.550_426 - 5723.265 / t + 3.530_68 * t.ln() - 0.007_283_32 * t).exp()
}

/// Давление насыщения над водой, которое используется во всех расчётах крейта, Па:
/// IAPWS (Wagner–Pruß) от 0.01 °C и выше, Murphy–Koop для переохлаждённой воды ниже.
pub fn p_sat(t_c: f64) -> f64 {
    if t_c >= 0.01 {
        p_sat_iapws_water(t_c)
    } else {
        p_sat_murphy_koop_water(t_c)
    }
}

/// Парциальное давление пара, Па, по относительной влажности (%, над водой).
pub fn vapour_pressure(t_c: f64, rh_percent: f64) -> f64 {
    rh_percent.clamp(0.0, 100.0) / 100.0 * p_sat(t_c)
}

