/// Предел силы квазистатического контакта с предплечьем/запястьем для коллаборативных роботов,
/// Н (ISO/TS 15066 по arXiv:2311.13814). Стандарт — о роботах, не об ортезах: ориентир, не норма.
pub const ISO_TS_15066_FOREARM_N: f64 = 160.0;

/// Участок тела для проверки контакта по ISO/TS 15066 (значения — табл. 1 в arXiv:2311.13814).
/// Стандарт написан для роботов, а пороги близки к началу боли и частично предварительные:
/// для ортеза это ориентир, а не гарантия отсутствия травмы.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ContactLimit {
    pub name: &'static str,
    /// Допустимая сила при зажиме (после окна удара), Н.
    pub quasi_static_n: f64,
    /// Эффективная жёсткость участка тела, Н/м.
    pub stiffness_n_per_m: f64,
    /// Эффективная масса участка тела, кг.
    pub mass_kg: f64,
}

