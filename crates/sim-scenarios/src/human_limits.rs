/// Давление манжеты на кожу (сдавление по окружности), кПа.
/// * до ~3–4 кПа — кровоток не страдает при долгой носке: венозный застой при ~2.9 кПа
///   (22 мм рт. ст.) за 5 мин (Landis & Gibbon 1933, doi:10.1172/jci100482), давление
///   в капиллярах ~4.3 кПа (32 мм рт. ст., классическое значение);
/// * от ~16 кПа — дискомфорт, от ~20 кПа — боль у здоровых (у людей с хронической болью —
///   от ~10 кПа), нестерпимо — 34–84 кПа (Kermavnar и др., 2018, doi:10.1089/soro.2017.0046,
///   doi:10.1089/soro.2017.0088).
pub const CUFF_PRESSURE_LONG_WEAR_KPA: f64 = 4.0;
pub const CUFF_PRESSURE_DISCOMFORT_KPA: f64 = 16.0;
pub const CUFF_PRESSURE_PAIN_KPA: f64 = 20.0;

