/// Регрессия пиковой силы по возрасту, росту и массе: M = a + b·возраст + c·рост + d·масса, Н·м.
/// Harbo, Brincks, Andersen, 2012, Eur J Appl Physiol 112:267, doi:10.1007/s00421-011-1975-3,
/// табл. 1 и 3 (178 здоровых, 15–83 года, Biodex). `rsd` — СКО остатка регрессии.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct HarboModel {
    pub intercept: f64,
    pub per_year: f64,
    pub per_metre: f64,
    pub per_kg: f64,
    pub rsd: f64,
}

const fn harbo(intercept: f64, per_year: f64, per_metre: f64, per_kg: f64, rsd: f64) -> HarboModel {
    HarboModel {
        intercept,
        per_year,
        per_metre,
        per_kg,
        rsd,
    }
}

