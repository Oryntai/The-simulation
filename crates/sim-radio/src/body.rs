//! Радиоканал на теле человека (2.4 ГГц) — по измерениям, собранным в модели канала
//! IEEE 802.15.6: Yazdandoost & Sayrafian, «Channel Model for Body Area Network (BAN)»,
//! IEEE P802.15-08-0780-12-0006, ноябрь 2010.
//!
//! Физика: ткани на 2.4 ГГц теряют ~3–4 дБ на сантиметр (см. [`crate::dielectric`]), поэтому
//! сквозь тело сигнал почти не идёт — он огибает тело поверхностной (ползущей) волной,
//! теряя ~2 дБ на каждый сантиметр пути по периметру, и доходит отражениями от комнаты.

/// Обстановка измерений модели CM3 (тело → тело).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum OnBodyRoom {
    /// Больничная палата (есть отражения от стен).
    Hospital,
    /// Безэховая камера (отражений нет).
    Anechoic,
}

/// CM3 на 2.4 ГГц, §8.2.5.A: PL(d) = a·lg d + b + N, d — расстояние между антеннами на
/// теле в мм. Возвращает (среднее, σ) в дБ. Палата: a = 6.6, b = 36.1, σ = 3.80;
/// безэховая камера: a = 29.3, b = −16.8, σ = 6.89.
pub fn on_body_cm3_db(d_mm: f64, room: OnBodyRoom) -> (f64, f64) {
    let (a, b, s) = match room {
        OnBodyRoom::Hospital => (6.6, 36.1, 3.80),
        OnBodyRoom::Anechoic => (29.3, -16.8, 6.89),
    };
    (a * d_mm.max(1.0).log10() + b, s)
}

/// Модель «вокруг тела» на 2.45 ГГц, §8.2.5.B: PL(d) = −10·lg(P0·e^(−m0·d) + P1),
/// где d — путь по периметру тела в см; P0 = −25.8 дБ (у антенны), m0 = 2.0 дБ/см (затухание
/// ползущей волны), P1 = −71.3 дБ (пол из отражений от помещения), σ = 3.6 дБ.
/// Возвращает (среднее, σ) в дБ.
pub fn around_body_db(perimeter_cm: f64) -> (f64, f64) {
    let p0 = -25.8;
    let m0 = 2.0;
    let p1 = -71.3;
    let lin = 10f64.powf((p0 - m0 * perimeter_cm.max(0.0)) / 10.0) + 10f64.powf(p1 / 10.0);
    (-10.0 * lin.log10(), 3.6)
}

/// Тело → внешний приёмник (CM4) на 2.36 ГГц, §8.2.8: передатчик на груди, приёмник в
/// 1–4 м. Средние потери, дБ: (d, видно стоя, не видно стоя, видно идя, не видно идя).
pub const OFF_BODY_2G36: [(f64, f64, f64, f64, f64); 4] = [
    (1.0, 53.81, 61.81, 44.46, 59.48),
    (2.0, 53.12, 68.64, 51.59, 70.30),
    (3.0, 56.04, 60.12, 52.14, 63.98),
    (4.0, 64.72, 63.10, 60.81, 62.56),
];

/// Средняя добавка от того, что тело закрывает антенну (не видно − видно) по таблице CM4,
/// усреднённая по 1–4 м и по стоянию/ходьбе, дБ. ≈ 9 дБ, разброс −2…19 дБ.
pub fn off_body_shadowing_mean_db() -> f64 {
    let mut s = 0.0;
    for &(_, ls, ns, lw, nw) in &OFF_BODY_2G36 {
        s += (ns - ls) + (nw - lw);
    }
    s / (2.0 * OFF_BODY_2G36.len() as f64)
}

/// Наибольшая добавка от тела в той же таблице, дБ (≈ 19 дБ: 2 м, идя).
pub fn off_body_shadowing_max_db() -> f64 {
    OFF_BODY_2G36
        .iter()
        .flat_map(|&(_, ls, ns, lw, nw)| [ns - ls, nw - lw])
        .fold(f64::MIN, f64::max)
}

/// Потери «устройство на теле → телефон» по таблице CM4 с линейной интерполяцией по lg d;
/// за 4 м продлеваем наклоном свободного пространства (20 дБ/декада). Стоя.
pub fn off_body_db(d_m: f64, line_of_sight: bool) -> f64 {
    let pick = |r: &(f64, f64, f64, f64, f64)| if line_of_sight { r.1 } else { r.2 };
    let t = &OFF_BODY_2G36;
    let d = d_m.max(0.2);
    if d <= t[0].0 {
        return pick(&t[0]) + 20.0 * (d / t[0].0).log10();
    }
    for w in t.windows(2) {
        if d <= w[1].0 {
            let x = (d.log10() - w[0].0.log10()) / (w[1].0.log10() - w[0].0.log10());
            return pick(&w[0]) + x * (pick(&w[1]) - pick(&w[0]));
        }
    }
    let last = &t[t.len() - 1];
    pick(last) + 20.0 * (d / last.0).log10()
}
