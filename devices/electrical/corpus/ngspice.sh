#!/bin/sh
# ngspice 47 принимает AREA=<число> у диода. Экспортёр отдаёт то же
# значение позиционным аргументом, который этот выпуск не распознаёт.
set -eu
awk '
    /^[dD][[:alnum:]_.]+[[:space:]]/ && NF == 5 &&
        $5 ~ /^[0-9]+([.][0-9]*)?([eE][+-]?[0-9]+)?$/ {
        $5 = "AREA=" $5
    }
    { print }
' | "${SIM_CORPUS_REAL_NGSPICE:?Нужен настоящий ngspice}" "$@"
